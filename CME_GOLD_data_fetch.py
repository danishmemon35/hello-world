        "            if 'Close' in data.columns and not data['Close'].isnull().all():\n",
        "                macd = ta.macd(data['Close'])\n",
        "                data = pd.concat([data, macd], axis=1)\n",
        "            else:\n",
        "                print(f\"Warning: 'Close' column missing or fully null for {ticker}. Skipping MACD calculation.\")\n",
        "\n",
        "            # Reset index and format date back to string as requested after all calculations\n",
        "            data = data.reset_index()\n",
        "            data['Date'] = data['Date'].dt.strftime('%Y-%m-%d %H:%M:%S')\n",
        "\n",
        "            # Reorder and select only the required columns, including all new indicator columns\n",
        "            required_cols = ['Date', 'Open', 'High', 'Low', 'Close', 'Volume', 'Value']\n",
        "            if 'EMA_50' in data.columns:\n",
        "                required_cols.extend(['EMA_50', 'EMA_200'])\n",
        "            if 'VWAP' in data.columns:\n",
        "                required_cols.append('VWAP')\n",
        "            # Add Bollinger Bands columns dynamically\n",
        "            bb_cols = [col for col in data.columns if col.startswith('BBL_') or col.startswith('BBM_') or col.startswith('BBU_')]\n",
        "            required_cols.extend(bb_cols)\n",
        "            if 'RSI' in data.columns:\n",
        "                required_cols.append('RSI')\n",
        "            # Add MACD columns dynamically\n",
        "            macd_cols = [col for col in data.columns if col.startswith('MACD_') or col.startswith('MACDh_') or col.startswith('MACDs_')]\n",
        "            required_cols.extend(macd_cols)\n",
        "\n",
        "            data = data[required_cols]\n",
        "\n",
        "            if sheet_id and worksheet_name: # Save to Google Sheets\n",
        "                try:\n",
        "                    spreadsheet = gc.open_by_key(sheet_id) # Changed open_by_id to open_by_key\n",
        "                    worksheet = spreadsheet.worksheet(worksheet_name)\n",
        "                    worksheet.clear() # Clear existing content\n",
        "                    set_with_dataframe(worksheet, data) # Write DataFrame to worksheet\n",
        "                    print(f\"Data for {ticker} (Interval: {interval_str}) successfully saved to Google Sheet: {worksheet_name}\")\n",
        "                    success_tickers.append(f\"{ticker} ({interval_str})\")\n",
        "                except Exception as gs_e:\n",
        "                    print(f\"Error saving data for {ticker} (Interval: {interval_str}) to Google Sheet: {str(gs_e)}\")\n",
        "                    traceback.print_exc()\n",
        "            else: # Save to Excel (original behavior)\n",
        "                # 3. Define the full path for the output file (e.g., HBL.xlsx)\n",
        "                output_file = os.path.join(OUTPUT_DIR, f\"{ticker}.xlsx\")\n",
        "\n",
        "                # Save to Excel\n",
        "                data.to_excel(output_file, index=False)\n",
        "                print(f\"Data for {ticker} successfully saved to {OUTPUT_DIR}/{ticker}.xlsx\")\n",
        "                success_tickers.append(ticker)\n",
        "\n",
        "        except Exception as e:\n",
        "            # Print error to console for debugging, but continue with the next ticker\n",
        "            print(f\"Error processing {ticker} (Interval: {interval_str}): {str(e)}\")\n",
