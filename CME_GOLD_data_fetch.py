        "\n",
        "            # Calculate RSI\n",
        "            if 'Close' in data.columns and not data['Close'].isnull().all():\n",
        "                data['RSI'] = ta.rsi(data['Close'])\n",
        "            else:\n",
        "                print(f\"Warning: 'Close' column missing or fully null for {ticker}. Skipping RSI calculation.\")\n",
        "\n",
