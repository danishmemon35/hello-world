        "import pandas as pd\n",
        "import tkinter as tk\n",
        "from tkinter import ttk, messagebox\n",
        "from tvDatafeed import TvDatafeed, Interval\n",
        "from datetime import datetime # Added for date handling\n",
        "import os\n",
        "import traceback\n",
        "import pandas_ta as ta # Import pandas_ta\n",
        "# gspread and gspread_dataframe imports will be handled in a separate cell for authentication\n",
        "\n",
        "# Define a reasonable default output directory for Colab/non-GUI use\n",
        "OUTPUT_DIR = \"./stock_data_downloads\"\n",
        "\n",
        "# Initialize tvDatafeed (Guest mode) for fetching historical data\n",
        "try:\n",
        "    tv = TvDatafeed()\n",
        "except Exception as e:\n",
        "    # Log warning but allow data fetching to proceed if possible\n",
        "    print(f\"Warning: Could not initialize TvDatafeed. Error: {e}\")\n",
        "    tv = None\n",
        "\n",
        "def validate_date(date_str):\n",
        "    \"\"\"Validates that a string is in YYYY-MM-DD format.\"\"\"\n",
        "    try:\n",
        "        datetime.strptime(date_str, '%Y-%m-%d')\n",
        "        return True\n",
        "    except ValueError:\n",
        "        return False\n",
        "\n",
        "def get_tv_interval(interval_str):\n",
        "    \"\"\"Maps interval strings to tvDatafeed Interval objects.\"\"\"\n",
        "    interval_map = {\n",
        "        \"1d\": Interval.in_daily,\n",
        "        \"1wk\": Interval.in_weekly,\n",
        "        \"1mo\": Interval.in_monthly,\n",
        "        \"4h\": Interval.in_4_hour  # Added mapping for 4-hour interval\n",
        "    }\n",
        "    return interval_map.get(interval_str)\n",
        "\n",
        "def fetch_and_save_data(raw_tickers_input, exchange_input, interval_str_input, start_date_str_input, end_date_str_input, sheet_id=None, worksheet_name=None):\n",
        "    \"\"\"\n",
        "    Fetches historical stock data from TradingView (for exchanges like PSX)\n",
        "    using a date range, and saves each ticker's data.\n",
        "    Can save to Excel or Google Sheets.\n",
        "    \"\"\"\n",
        "    if tv is None:\n",
        "        print(\"Error: Failed to initialize TvDatafeed. Check network connection or library installation.\")\n",
        "        return\n",
        "\n",
        "    raw_tickers = raw_tickers_input.strip().upper()\n",
        "    exchange = exchange_input.strip().upper()\n",
        "    interval_str = interval_str_input\n",
        "\n",
        "    start_date_str = start_date_str_input.strip()\n",
        "    end_date_str = end_date_str_input.strip()\n",
        "\n",
        "    # Split the input string by comma and clean up spaces, filtering out empty entries\n",
        "    tickers = [t.strip() for t in raw_tickers.split(',') if t.strip()]\n",
        "\n",
        "    # Input validation\n",
        "    if not tickers:\n",
        "        print(\"Error: Please enter at least one ticker symbol.\")\n",
        "        return\n",
        "    if not exchange:\n",
        "        print(\"Error: Please enter the exchange (e.g., PSX).\")\n",
        "        return\n",
        "    if not validate_date(start_date_str):\n",
        "        print(\"Error: Please enter a valid start date (YYYY-MM-DD).\")\n",
        "        return\n",
        "    if not validate_date(end_date_str):\n",
        "        print(\"Error: Please enter a valid end date (YYYY-MM-DD).\")\n",
        "        return\n",
        "\n",
        "    try:\n",
        "        # Calculate approximate number of bars needed to cover the date range\n",
        "        start_dt = datetime.strptime(start_date_str, '%Y-%m-%d').date()\n",
        "        end_dt = datetime.strptime(end_date_str, '%Y-%m-%d').date()\n",
        "\n",
        "        # Calculate days difference and multiply by a factor (e.g., 2.5) for safety (weekends/holidays)\n",
        "        time_delta = (end_dt - start_dt).days\n",
        "        n_bars_approx = int(time_delta * 2.5) + 5\n",
        "\n",
        "        # Ensure n_bars is at least 100 for reliable fetch\n",
        "        n_bars = max(n_bars_approx, 100)\n",
        "    except Exception:\n",
        "        print(\"Error: Invalid date format or range.\")\n",
        "        return\n",
        "\n",
        "    tv_interval = get_tv_interval(interval_str)\n",
        "\n",
        "    # Define the output directory and ensure it exists if saving to Excel\n",
        "    if not sheet_id:\n",
        "        os.makedirs(OUTPUT_DIR, exist_ok=True)\n",
        "\n",
        "    success_tickers = []\n",
        "\n",
        "    # Loop through each ticker and process them individually\n",
        "    for ticker in tickers:\n",
        "        try:\n",
        "            # Fetch historical data using tvDatafeed with approximated bars\n",
        "            data = tv.get_hist(\n",
        "                symbol=ticker,\n",
        "                exchange=exchange,\n",
        "                interval=tv_interval,\n",
        "                n_bars=n_bars\n",
        "            )\n",
        "\n",
        "            if data is None or data.empty:\n",
        "                print(f\"Warning: No data found for {ticker} on {exchange}. Skipping.\")\n",
        "                continue\n",
        "\n",
        "            # --- START OF FIX: Robust column renaming ---\n",
        "            # data index is already a datetime index, we reset it\n",
        "            data = data.reset_index()\n",
        "\n",
        "            # Determine the name of the column containing the date/time data after reset_index\n",
        "            date_col_original = None\n",
        "            # Check common possible names for the datetime column after reset_index()\n",
        "            for col in ['time', 'datetime', 'index']:\n",
        "                if col in data.columns:\n",
        "                    date_col_original = col\n",
        "                    break\n",
        "\n",
        "            if date_col_original is None:\n",
        "                # If we still can't find it, skip the ticker and report error\n",
        "                raise KeyError(f\"Could not find a valid date column in DataFrame for {ticker}.\")\n",
        "\n",
        "            # Rename the identified date column to 'Date' and ensure other columns are Title Case\n",
        "            column_mapping = {\n",
        "                date_col_original: 'Date',\n",
        "                'open': 'Open',\n",
        "                'high': 'High',\n",
        "                'low': 'Low',\n",
        "                'close': 'Close',\n",
        "                'volume': 'Volume'\n",
        "            }\n",
        "\n",
        "            data.rename(columns=column_mapping, inplace=True)\n",
        "\n",
        "            # Drop the 'symbol' column which is redundant for single-ticker output\n",
        "            if 'symbol' in data.columns:\n",
        "                data.drop(columns=['symbol'], inplace=True)\n",
        "            # --- END OF FIX ---\n",
        "\n",
        "            # Ensure 'Date' column is datetime type before setting as index\n",
        "            data['Date'] = pd.to_datetime(data['Date'])\n",
        "            data.set_index('Date', inplace=True)\n",
        "\n",
        "            # Filter the DataFrame to the exact date range requested\n",
        "            data = data.loc[start_date_str:end_date_str]\n",
        "\n",
        "            # 1. Calculate the new 'Value' column (Close * Volume)\n",
        "            if 'Close' in data.columns and 'Volume' in data.columns:\n",
        "                data['Close'] = pd.to_numeric(data['Close'], errors='coerce')\n",
        "                data['Volume'] = pd.to_numeric(data['Volume'], errors='coerce')\n",
        "                data['Value'] = data['Close'] * data['Volume']\n",
        "            else:\n",
        "                print(f\"Error: Required columns ('Close' or 'Volume') missing for {ticker}. Skipping.\")\n",
        "                continue\n",
        "\n",
        "            # Calculate EMAs after ensuring 'Close' column is numeric\n",
        "            if 'Close' in data.columns and not data['Close'].isnull().all():\n",
        "                data['EMA_50'] = ta.ema(data['Close'], length=50)\n",
        "                data['EMA_200'] = ta.ema(data['Close'], length=200)\n",
        "\n",
        "            # Calculate VWAP\n",
        "            if all(col in data.columns for col in ['High', 'Low', 'Close', 'Volume']) and not data[['High', 'Low', 'Close', 'Volume']].isnull().all().any():\n",
        "                data['VWAP'] = ta.vwap(data['High'], data['Low'], data['Close'], data['Volume'])\n",
        "            else:\n",
        "                print(f\"Warning: Required columns for VWAP missing or fully null for {ticker}. Skipping VWAP calculation.\")\n",
        "\n",
        "            # Calculate Bollinger Bands\n",
        "            if 'Close' in data.columns and not data['Close'].isnull().all():\n",
